<?php

namespace App\Http\Controllers\Web;

use App\Http\Controllers\Controller;
use App\Http\Requests\Web\ReplySupportTicketRequest;
use App\Http\Requests\Web\StoreSupportTicketRequest;
use App\Mail\SupportTicketCreatedMail;
use App\Models\AdminNotification;
use App\Models\SupportTicket;
use App\Models\SupportTicketMessage;
use App\Models\User;
use Illuminate\Contracts\View\View;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Str;

class SupportTicketController extends Controller
{
    /**
     * Show public support ticket creation form (Guests & Users).
     */
    public function create(): View
    {
        $user = auth()->user();

        return view('web.pages.support.create', compact('user'));
    }

    /**
     * Store new support ticket generated by customer or guest.
     */
    public function store(StoreSupportTicketRequest $request): RedirectResponse
    {
        $user = auth()->user();

        // If guest provided an email that belongs to a registered customer, link it
        if (! $user && $request->filled('email')) {
            $user = User::where('email', $request->email)->first();
        }

        $ticket = SupportTicket::create([
            'ticket_number' => SupportTicket::generateTicketNumber(),
            'user_id' => $user?->id,
            'customer_name' => $request->name,
            'customer_email' => $request->email,
            'customer_phone' => $request->phone,
            'subject' => $request->subject,
            'priority' => $request->priority ?? 'normal',
            'status' => 'open',
            'created_by' => 'customer',
            'access_token' => Str::random(40),
            'last_reply_at' => now(),
        ]);

        // Strictly text message only - initial customer inquiry
        SupportTicketMessage::create([
            'support_ticket_id' => $ticket->id,
            'sender_type' => 'customer',
            'sender_id' => $user?->id,
            'sender_name' => $request->name,
            'message' => $request->message,
        ]);

        // Trigger real-time sound alert notification for admin team
        AdminNotification::create([
            'type' => 'support_ticket',
            'title' => "New Support Ticket: #{$ticket->ticket_number}",
            'message' => "Client {$ticket->customer_name} ({$ticket->customer_email}) submitted: {$ticket->subject}",
            'is_read' => false,
            'sound_played' => false,
        ]);

        // Send confirmation email to customer
        Mail::to($ticket->customer_email)
            ->send(new SupportTicketCreatedMail($ticket, $ticket->access_token));

        if (auth()->check()) {
            return redirect()
                ->route('customer.tickets.show', $ticket->ticket_number)
                ->with('success', "Support ticket #{$ticket->ticket_number} created successfully. Our engineering desk is on it.");
        }

        return redirect()
            ->route('support.show', [
                'ticketNumber' => $ticket->ticket_number,
                'token' => $ticket->access_token,
            ])
            ->with('success', "Support ticket #{$ticket->ticket_number} generated successfully. Please bookmark this page or keep your token to check updates.");
    }

    /**
     * Public ticket viewer (Accessible with valid token or matching credentials).
     */
    public function show(Request $request, string $ticketNumber): View|RedirectResponse
    {
        $cleanNumber = ltrim(trim($ticketNumber), '#');
        $ticket = SupportTicket::with(['messages', 'user'])
            ->where(function ($q) use ($cleanNumber, $ticketNumber) {
                $q->where('ticket_number', $cleanNumber)
                    ->orWhere('ticket_number', $ticketNumber);
            })
            ->firstOrFail();

        $token = $request->query('token');
        $user = auth()->user();

        $isAuthorized = false;

        if ($user && ($ticket->user_id === $user->id || strcasecmp((string) $ticket->customer_email, (string) $user->email) === 0)) {
            $isAuthorized = true;
        } elseif ($token && hash_equals($ticket->access_token, (string) $token)) {
            $isAuthorized = true;
        } elseif ($request->filled('email') && strcasecmp((string) $ticket->customer_email, (string) $request->email) === 0) {
            $isAuthorized = true;
        }

        if (! $isAuthorized) {
            return redirect()
                ->route('support.track')
                ->with('error', 'Please enter your ticket number and matching email address to access ticket details.')
                ->with('prefill_ticket', $ticketNumber);
        }

        return view('web.pages.support.show', compact('ticket', 'token'));
    }

    /**
     * Post a reply to ticket from customer/guest (Strictly text only).
     */
    public function reply(ReplySupportTicketRequest $request, string $ticketNumber): RedirectResponse
    {
        $cleanNumber = ltrim(trim($ticketNumber), '#');
        $ticket = SupportTicket::where(function ($q) use ($cleanNumber, $ticketNumber) {
            $q->where('ticket_number', $cleanNumber)
                ->orWhere('ticket_number', $ticketNumber);
        })->firstOrFail();

        $user = auth()->user();
        $token = $request->input('token');

        $isAuthorized = false;
        if ($user && ($ticket->user_id === $user->id || strcasecmp((string) $ticket->customer_email, (string) $user->email) === 0)) {
            $isAuthorized = true;
        } elseif ($token && hash_equals($ticket->access_token, (string) $token)) {
            $isAuthorized = true;
        } elseif ($request->filled('email') && strcasecmp((string) $ticket->customer_email, (string) $request->email) === 0) {
            $isAuthorized = true;
        }

        if (! $isAuthorized) {
            abort(403, 'Unauthorized ticket access.');
        }

        $senderName = $user?->name ?? $ticket->customer_name;

        SupportTicketMessage::create([
            'support_ticket_id' => $ticket->id,
            'sender_type' => 'customer',
            'sender_id' => $user?->id,
            'sender_name' => $senderName,
            'message' => $request->message,
        ]);

        // Re-open ticket if it was closed
        $ticket->status = 'open';
        $ticket->closed_at = null;
        $ticket->last_reply_at = now();
        $ticket->save();

        AdminNotification::create([
            'type' => 'support_ticket',
            'title' => "Customer Replied to Ticket #{$ticket->ticket_number}",
            'message' => "{$senderName} sent a new response on: {$ticket->subject}",
            'is_read' => false,
            'sound_played' => false,
        ]);

        $redirectRoute = $user
            ? redirect()->route('customer.tickets.show', $ticket->ticket_number)
            : redirect()->route('support.show', ['ticketNumber' => $ticket->ticket_number, 'token' => $ticket->access_token]);

        return $redirectRoute->with('success', 'Your reply has been dispatched to the support engineering team.');
    }

    /**
     * Public search/lookup form to check status by Ticket Number + Email.
     * Shows current user's tickets if logged in.
     */
    public function track(Request $request): View|RedirectResponse
    {
        $user = auth()->user();

        if ($request->isMethod('post')) {
            $rawNumber = trim((string) $request->ticket_number);
            $cleanNumber = strtoupper(ltrim($rawNumber, '#'));
            $cleanNumber = trim($cleanNumber);

            $rules = [
                'ticket_number' => ['required', 'string'],
            ];

            // If user is guest, email is required to verify ownership
            if (! $user) {
                $rules['email'] = ['required', 'email'];
            } else {
                $rules['email'] = ['nullable', 'email'];
            }

            $request->validate($rules);

            $email = $request->filled('email')
                ? strtolower(trim((string) $request->email))
                : ($user ? strtolower(trim((string) $user->email)) : null);

            $query = SupportTicket::where(function ($q) use ($cleanNumber, $rawNumber) {
                $q->where('ticket_number', $cleanNumber)
                    ->orWhere('ticket_number', $rawNumber)
                    ->orWhereRaw('UPPER(ticket_number) = ?', [$cleanNumber]);
            });

            if ($email) {
                $query->where(function ($q) use ($email, $user) {
                    $q->whereRaw('LOWER(TRIM(customer_email)) = ?', [$email]);
                    if ($user) {
                        $q->orWhere('user_id', $user->id);
                    }
                });
            } elseif ($user) {
                $query->where('user_id', $user->id);
            }

            $ticket = $query->first();

            if (! $ticket) {
                return back()->withInput()->with('error', 'No support ticket found matching this ticket number'.($email ? ' and email address.' : '.'));
            }

            if ($user && ($ticket->user_id === $user->id || strtolower(trim($ticket->customer_email)) === strtolower(trim($user->email)))) {
                return redirect()->route('customer.tickets.show', $ticket->ticket_number);
            }

            return redirect()->route('support.show', [
                'ticketNumber' => $ticket->ticket_number,
                'token' => $ticket->access_token,
            ]);
        }

        // For GET request:
        // If user is logged in, fetch their tickets!
        $myTickets = collect();
        if ($user) {
            $myTickets = SupportTicket::where(function ($q) use ($user) {
                $q->where('user_id', $user->id)
                    ->orWhereRaw('LOWER(TRIM(customer_email)) = ?', [strtolower(trim($user->email))]);
            })
                ->with('messages')
                ->orderByDesc('updated_at')
                ->get();
        }

        return view('web.pages.support.track', compact('myTickets'));
    }

    /**
     * Authenticated Customer Portal: List all tickets for current logged-in user.
     */
    public function customerIndex(): View
    {
        $user = auth()->user();

        $tickets = SupportTicket::where(function ($q) use ($user) {
            $q->where('user_id', $user->id)
                ->orWhereRaw('LOWER(TRIM(customer_email)) = ?', [strtolower(trim($user->email))]);
        })
            ->with('messages')
            ->orderByDesc('updated_at')
            ->paginate(10);

        return view('web.pages.customer.tickets-index', compact('tickets'));
    }

    /**
     * Authenticated Customer Portal: View ticket details & step-by-step chat flow.
     */
    public function customerShow(string $ticketNumber): View
    {
        $user = auth()->user();
        $cleanNumber = ltrim(trim($ticketNumber), '#');

        $ticket = SupportTicket::with(['messages', 'user', 'admin'])
            ->where(function ($q) use ($cleanNumber, $ticketNumber) {
                $q->where('ticket_number', $cleanNumber)
                    ->orWhere('ticket_number', $ticketNumber);
            })
            ->where(function ($q) use ($user) {
                $q->where('user_id', $user->id)
                    ->orWhereRaw('LOWER(TRIM(customer_email)) = ?', [strtolower(trim($user->email))]);
            })
            ->firstOrFail();

        return view('web.pages.customer.ticket-details', compact('ticket'));
    }
}
